package com.airconcepts.dashboard.forecast.excel;
import com.airconcepts.dashboard.forecast.calc.*;
import com.airconcepts.dashboard.forecast.calc.ForecastResult.Contribution;
import com.airconcepts.dashboard.forecast.excel.WorkbookFailure.Problem;
import java.math.BigDecimal;
import java.time.*;
import java.util.*;
import java.util.stream.Collectors;
import org.apache.poi.ss.usermodel.*;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;
import org.springframework.stereotype.Component;
@Component
public class WorkbookPopulator {
  private record Group(String label,Set<UUID> ids,BigDecimal monthlyCost){}
  public List<String> populate(XSSFWorkbook w,ForecastDataset data,ForecastResult result,Instant generated){
    var receipts=result.contributions().stream().filter(c->c.source().equals("DOCUMENT")&&c.direction().equals("IN")).toList();
    var payments=result.contributions().stream().filter(c->c.source().equals("DOCUMENT")&&c.direction().equals("OUT")).toList();
    if(receipts.size()>200||payments.size()>200)throw new WorkbookFailure("FORECAST_TEMPLATE_CAPACITY","The template holds at most 200 contributions on each Xero sheet.",
        List.of(new Problem("Xero_Debtors","A5:G204","Receipts: "+receipts.size()+"; payments: "+payments.size()+". Split lines count individually.")));
    List<String> warnings=new ArrayList<>();var assumptions=w.getSheet("Assumptions");var forecast=WorkbookValidator.forecast(w);var staff=w.getSheet("Staffing");
    String name=data.entityName().toUpperCase(Locale.ROOT);
    value(assumptions,0,0,name+" - CASH FLOW ASSUMPTIONS");value(forecast,0,0,name+" MONTHLY CASH FLOW");value(staff,0,0,name);value(staff,8,0,name);value(staff,21,0,name);
    value(assumptions,3,1,data.startMonth().atDay(1));value(assumptions,4,1,data.openingBalance());value(assumptions,4,2,"Source: "+Objects.toString(data.openingBalanceSource(),"Not recorded"));
    value(assumptions,5,1,0);value(assumptions,6,1,0);value(assumptions,7,2,"Generated by Air Concepts dashboard at "+generated.atZone(com.airconcepts.dashboard.time.BusinessTime.ZONE)+", template v1. GST-inclusive cash amounts.");
    writeXero(w.getSheet("Xero_Debtors"),receipts,data);writeXero(w.getSheet("Xero_Creditors"),payments,data);
    contacts(forecast,7,15,receipts);contacts(forecast,28,20,payments);
    for(int m=0;m<12;m++){final YearMonth month=data.startMonth().plusMonths(m);value(forecast,24,m+1,sum(result.contributions().stream().filter(c->c.source().equals("MANUAL")&&c.direction().equals("IN")&&c.bucket().equals(month)).toList()));}
    var manual=data.manualItems().stream().filter(i->i.active()&&i.direction().equals("OUT"))
        .map(i->new Group(i.description(),Set.of(i.id()),i.amount())).sorted(groupOrder(result,"MANUAL")).toList();
    var manualGroups=aggregate(manual,10,"Other payments",warnings);
    for(int i=0;i<10;i++){
      Group group=i<manualGroups.size()?manualGroups.get(i):null;value(forecast,55+i,0,group==null?null:group.label());
      for(int m=0;m<12;m++)value(forecast,55+i,m+1,group==null?null:monthly(result,"MANUAL",group.ids(),data.startMonth().plusMonths(m)));
    }
    var employees=data.staffing().stream().filter(ForecastDataset.StaffingLine::active).map(i->new Group(i.label(),Set.of(i.id()),i.monthlyCost())).sorted(groupOrder(result,"STAFFING")).toList();
    var groups=aggregate(employees,6,"Other staff",warnings);
    for(int i=0;i<6;i++){
      for(int c=0;c<9;c++)value(staff,9+i,c,null);
      if(i<groups.size()){var group=groups.get(i);value(staff,9+i,2,group.label());value(staff,9+i,7,group.monthlyCost());value(staff,9+i,8,"Dashboard staffing line");}
    }
    for(int m=0;m<12;m++){
      var month=data.startMonth().plusMonths(m);value(staff,18,m+3,month.atDay(1));
      int mondays=0;for(int day=1;day<=month.lengthOfMonth();day++)if(month.atDay(day).getDayOfWeek()==DayOfWeek.MONDAY)mondays++;
      value(staff,19,m+3,mondays);
    }
    for(int i=0;i<7;i++){
      Group group=i<groups.size()?groups.get(i):null;value(staff,22+i,0,null);value(staff,22+i,1,null);value(staff,22+i,2,group==null?null:group.label());
      for(int m=0;m<12;m++){
        var month=data.startMonth().plusMonths(m);var active=group==null?List.<Contribution>of():result.contributions().stream().filter(c->c.source().equals("STAFFING")&&group.ids().contains(c.sourceId())&&c.bucket().equals(month)).toList();
        value(staff,22+i,3+m,active.isEmpty()?null:sum(active));
      }
    }
    for(int r=18;r<=29;r++)for(int c=15;c<=65;c++)value(staff,r,c,null);
    int endYear=data.startMonth().plusMonths(11).getYear();w.setSheetName(w.getSheetIndex(forecast),"Forecast "+data.startMonth().getYear()+"-"+endYear);
    w.setForceFormulaRecalculation(true);return List.copyOf(warnings);
  }
  private static void writeXero(Sheet sheet,List<Contribution> rows,ForecastDataset data){
    var documents=data.documents().stream().collect(Collectors.toMap(ForecastDataset.Document::id,d->d));
    for(int i=0;i<200;i++){
      for(int c=0;c<6;c++)value(sheet,i+4,c,null);
      if(i>=rows.size())continue;var item=rows.get(i);var doc=documents.get(item.sourceId());
      String number=doc.number()==null?doc.id().toString().substring(0,8):doc.number();if(item.splitSequence()!=null)number+=" ("+item.splitSequence()+"/"+item.splitCount()+")";
      value(sheet,i+4,0,doc.contact());value(sheet,i+4,1,number);value(sheet,i+4,2,doc.issueDate());value(sheet,i+4,3,doc.dueDate()==null?doc.issueDate():doc.dueDate());value(sheet,i+4,4,item.amount());value(sheet,i+4,5,item.bucket().atDay(1));
    }
  }
  private static void contacts(Sheet sheet,int start,int count,List<Contribution> rows){
    Map<String,BigDecimal> totals=new HashMap<>();for(var c:rows)totals.merge(c.label(),c.amount(),BigDecimal::add);
    var names=totals.entrySet().stream().sorted(Map.Entry.<String,BigDecimal>comparingByValue().reversed().thenComparing(Map.Entry::getKey)).map(Map.Entry::getKey).toList();
    for(int i=0;i<count;i++)value(sheet,start+i,0,i<names.size()?names.get(i):null);
  }
  private static Comparator<Group> groupOrder(ForecastResult result,String source){return Comparator.<Group,BigDecimal>comparing(g->sum(result.contributions().stream().filter(c->c.source().equals(source)&&g.ids().contains(c.sourceId())).toList())).reversed().thenComparing(Group::label).thenComparing(g->g.ids().iterator().next().toString());}
  private static List<Group> aggregate(List<Group> groups,int cap,String label,List<String> warnings){
    if(groups.size()<=cap)return groups;var output=new ArrayList<>(groups.subList(0,cap-1));var rest=groups.subList(cap-1,groups.size());
    Set<UUID> ids=new HashSet<>();var cost=BigDecimal.ZERO;for(var g:rest){ids.addAll(g.ids());cost=cost.add(g.monthlyCost());}
    String message=label+" ("+rest.size()+(label.equals("Other staff")?" lines)":" items)");output.add(new Group(message,ids,cost));warnings.add(message+" aggregated into the final template row.");return output;
  }
  private static BigDecimal monthly(ForecastResult result,String source,Set<UUID> ids,YearMonth month){return sum(result.contributions().stream().filter(c->c.source().equals(source)&&ids.contains(c.sourceId())&&c.bucket().equals(month)).toList());}
  private static BigDecimal sum(List<Contribution> rows){return rows.stream().map(Contribution::amount).reduce(new BigDecimal("0.00"),BigDecimal::add);}
  private static void value(Sheet sheet,int row,int column,Object value){
    var r=sheet.getRow(row);if(r==null)r=sheet.createRow(row);var cell=r.getCell(column);if(cell==null)cell=r.createCell(column);
    cell.setBlank();if(value instanceof LocalDate date)cell.setCellValue(date);else if(value instanceof Number number)cell.setCellValue(number.doubleValue());else if(value!=null)cell.setCellValue(value.toString());
  }
}
